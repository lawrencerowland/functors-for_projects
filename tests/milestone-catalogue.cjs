const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const dom = new JSDOM(home, { runScripts: 'dangerously', url: 'https://example.test/functors-for_projects/' });
const d = dom.window.document;
assert.equal(d.querySelectorAll('a[href="apps/fibration-milestone-linking/index.html"]').length, 1);
assert.equal(d.querySelectorAll('a[href*="fibration_example_v2"]').length, 0);
assert.equal(d.querySelectorAll('.app-card').length, 16);
const search = d.querySelector('#app-search');
search.value = 'milestone';
search.dispatchEvent(new dom.window.Event('input'));
assert.equal([...d.querySelectorAll('.app-card')].filter(x => !x.hidden).length, 1);
assert.match(d.querySelector('#app-count').textContent, /1 of 16/);
search.value = '';
search.dispatchEvent(new dom.window.Event('input'));
assert.match(d.querySelector('#app-count').textContent, /16 of 16/);
const redirect = fs.readFileSync(path.join(root, 'apps/fibration_example_v2/index.html'), 'utf8');
assert.match(redirect, /fibration-milestone-linking/);
assert.match(redirect, /location.search/);
assert.match(redirect, /location.hash/);
assert.match(redirect, /href=["'][^"']*fibration-milestone-linking/);
dom.window.close();
console.log('PASS: one milestone catalogue entry, 16 total apps, search/reset, old-URL fallback and query/fragment preservation.');
